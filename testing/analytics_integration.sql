    away_wp         DOUBLE PRECISION NOT NULL,
    market_wp       DOUBLE PRECISION,
    game_date       DATE,
    season          VARCHAR(10),
    season_type     VARCHAR(20),
    game_status     VARCHAR(20),
    scraped_at      TIMESTAMP,
