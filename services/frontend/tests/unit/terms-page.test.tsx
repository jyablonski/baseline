import { render, screen, within } from "@testing-library/react";
import { beforeEach, describe, expect, it, vi } from "vitest";

const features = vi.hoisted(() => ({ get: vi.fn() }));
vi.mock("@/lib/api", () => ({ api: { getFeatures: features.get } }));

import TermsPage from "@/app/terms/page";
import { Providers } from "@/components/providers";

function renderTerms() {
  render(
    <Providers>
      <TermsPage />
    </Providers>
  );
  return screen.getByRole("article");
}

describe("terms page", () => {
  beforeEach(() => {
    features.get.mockReset();
  });

  it("says stakes are play money and the data comes as is", () => {
    features.get.mockResolvedValue({ chatbot: false, picks: true });
    const terms = renderTerms();

    expect(screen.getByRole("heading", { name: "Terms" })).toBeInTheDocument();
    expect(screen.getAllByRole("heading", { level: 2 }).map((node) => node.textContent)).toEqual([
      "Picks and stakes",
      "The data",
      "Accounts",
      "Affiliation",
      "Availability and changes",
    ]);
    expect(terms).toHaveTextContent(/A stake is play money: it has no cash value/);
    expect(terms).toHaveTextContent(/is not a gambling service/);
    expect(terms).toHaveTextContent(/provided as is/);
    expect(terms).not.toHaveTextContent(/chat/i);
    expect(within(terms).getByRole("link", { name: "privacy policy" })).toHaveAttribute(
      "href",
      "/privacy"
    );
    expect(within(terms).getByRole("link", { name: "account page" })).toHaveAttribute(
      "href",
      "/account"
    );
  });

  it("covers chat only while chat is offered", async () => {
    features.get.mockResolvedValue({ chatbot: true, picks: true });
    const terms = renderTerms();

    expect(await screen.findByRole("heading", { name: "Chat" })).toBeInTheDocument();
    expect(terms).toHaveTextContent(/generated by an AI model/);
  });
});
