#!/usr/bin/env python3
"""Keep docs/features/*.md honest against the code they describe.

  check            front matter is valid, every code: / related: path exists,
                   and the README index matches the docs (exit 1 otherwise)
  index            rewrite the index table in docs/features/README.md
  for PATH...      print the feature doc(s) whose code: paths cover each PATH
  changed PATH...  warn about features whose code changed without their doc;
                   always exits 0 (a reminder, not a gate)

Stdlib only, so it runs under the host python3 and in pre-commit unchanged.
"""

from __future__ import annotations

import fnmatch
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FEATURES = os.path.join("docs", "features")
README = os.path.join(FEATURES, "README.md")
INDEX_START = "<!-- feature-index:start (generated by scripts/feature-docs.py index) -->"
INDEX_END = "<!-- feature-index:end -->"
STATUSES = {"current", "planned"}


def parse(path: str) -> dict:
    """Read the front matter: scalar `key: value` lines and `  - item` lists."""
    with open(os.path.join(ROOT, path)) as handle:
        text = handle.read()
    meta: dict = {"path": path, "errors": []}
    if not text.startswith("---\n"):
        meta["errors"].append("no front matter")
        return meta
    block, _, body = text[4:].partition("\n---\n")
    key = None
    for line in block.splitlines():
        if item := re.match(r"^\s+-\s+(.+)$", line):
            if key is None or not isinstance(meta.get(key), list):
                meta["errors"].append(f"list item outside a list: {line.strip()}")
                continue
            meta[key].append(item.group(1).strip())
        elif pair := re.match(r"^([a-z_]+):\s*(.*)$", line):
            key, value = pair.group(1), pair.group(2).strip()
            meta[key] = value if value else []
        elif line.strip():
            meta["errors"].append(f"unreadable front matter line: {line}")
    title = re.search(r"^# (.+)$", body, re.M)
    meta["title"] = title.group(1).strip() if title else os.path.basename(path)
    return meta


def feature_docs() -> list[dict]:
    paths = sorted(glob.glob(os.path.join(ROOT, FEATURES, "*.md")))
    return [parse(os.path.relpath(p, ROOT)) for p in paths if not p.endswith("README.md")]


def path_exists(entry: str) -> bool:
    # Literal first: route folders like app/games/[id]/ are not glob classes.
    if os.path.exists(os.path.join(ROOT, entry)):
        return True
    return "*" in entry and bool(glob.glob(os.path.join(ROOT, entry.replace("[", "[[]"))))


def covers(entry: str, path: str) -> bool:
    if entry.endswith("/"):
        return path.startswith(entry)
    if "*" in entry:
        return fnmatch.fnmatchcase(path, entry.replace("[", "[[]"))
    return path == entry


def render_index(docs: list[dict]) -> str:
    rows = ["| Feature | Status | Summary |", "|---|---|---|"]

    def cell(text: str) -> str:
        return text.replace("|", "\\|")

    for doc in docs:
        name = os.path.basename(doc["path"])
        rows.append(
            f"| [{cell(doc['title'])}]({name}) | {doc.get('status', '')} | {cell(doc.get('summary', ''))} |"
        )
    return "\n".join([INDEX_START, "", *rows, "", INDEX_END])


def current_index() -> str | None:
    with open(os.path.join(ROOT, README)) as handle:
        text = handle.read()
    match = re.search(re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END), text, re.S)
    return match.group(0) if match else None


def normalized(table: str) -> list[str]:
    """Table rows with cell padding and separator widths removed, since prettier realigns them."""
    rows = []
    for line in table.splitlines():
        if not line.startswith("|"):
            rows.append(line.strip())
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        rows.append("|".join("---" if re.fullmatch(r":?-+:?", cell) else cell for cell in cells))
    return [row for row in rows if row]


def check() -> int:
    problems: list[str] = []
    docs = feature_docs()
    for doc in docs:
        where = doc["path"]
        problems += [f"{where}: {error}" for error in doc["errors"]]
        if not doc.get("summary"):
            problems.append(f"{where}: missing summary")
        if doc.get("status") not in STATUSES:
            problems.append(f"{where}: status must be one of {sorted(STATUSES)}")
        if not doc.get("code"):
            problems.append(f"{where}: no code: paths")
        for key in ("code", "related"):
            for entry in doc.get(key) or []:
                if not path_exists(entry):
                    problems.append(f"{where}: {key} path does not exist: {entry}")
    index = current_index()
    if index is None:
        problems.append(f"{README}: index markers missing")
    elif normalized(index) != normalized(render_index(docs)):
        problems.append(f"{README}: index is stale; run `python3 scripts/feature-docs.py index`")
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


def write_index() -> int:
    path = os.path.join(ROOT, README)
    with open(path) as handle:
        text = handle.read()
    if current_index() is None:
        print(f"{README}: add the index markers first", file=sys.stderr)
        return 1
    start, end = text.index(INDEX_START), text.index(INDEX_END) + len(INDEX_END)
    with open(path, "w") as handle:
        handle.write(text[:start] + render_index(feature_docs()) + text[end:])
    return 0


def docs_for(paths: list[str]) -> int:
    docs = feature_docs()
    for path in paths:
        matches = [d["path"] for d in docs if any(covers(e, path) for e in d.get("code") or [])]
        print(f"{path}: {', '.join(matches) if matches else 'no feature doc'}")
    return 0


def changed(paths: list[str]) -> int:
    touched = set(paths)
    for doc in feature_docs():
        hits = [p for p in paths if any(covers(e, p) for e in doc.get("code") or [])]
        if hits and doc["path"] not in touched:
            print(
                f"note: {doc['path']} covers {len(hits)} changed file(s) ({hits[0]}…) but was not updated"
            )
    return 0


def main(argv: list[str]) -> int:
    command, args = (argv[0], argv[1:]) if argv else ("", [])
    if command == "check":
        return check()
    if command == "index":
        return write_index()
    if command == "for" and args:
        return docs_for(args)
    if command == "changed":
        return changed(args)
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
